SCRIPT_SHA='a9bb4075285df9acf2bf75c08446d44cfd83b29f6940937671cc07bd68f9f6cc'
ROMAN_SHA='9ba7c6f12d40ea8a0aafb8f07a69f8b65b424e374c6da95235a45edeb6292c52'
MODES={'translation':'English translation','transliteration':'Transliteration 7 · intended Roman forms','literal':'Times New Roman · literal slots'}


def policy():
    return dict(formatVersion='1.0.0',orthographyId='thimfora-79',scriptFontSha256=SCRIPT_SHA,transliterationFontSha256=ROMAN_SHA,defaultMode='transliteration',normalization='none')


def validate(snapshot):
    p=snapshot['reading']
    if p!=policy():raise ValueError('READING_UNSUPPORTED_PROFILE')
    orth=next((o for o in snapshot['language']['orthographies'] if o['id']==p['orthographyId']),None)
    if orth is None or p['scriptFontSha256'] not in orth['fontSha256s']:raise ValueError('READING_ORTHOGRAPHY_MISMATCH')


def font(book,mode):
    if mode not in MODES:raise ValueError('READING_MODE_INVALID')
    if mode=='translation':return None
    if mode=='transliteration':return book.fonts.resolve('font:'+ROMAN_SHA+':0')
    path=Path(os.environ.get('WINDIR','C:/Windows'))/'Fonts/times.ttf'
    if not path.is_file():raise ValueError('READING_TIMES_NEW_ROMAN_MISSING')
    face=book.fonts.register(path)
    if face.original_family!='Times New Roman':raise ValueError('READING_TIMES_NEW_ROMAN_IDENTITY')
    return face


def inspect(snapshot,test_id,mode='transliteration'):
    if mode not in MODES:raise ValueError('READING_MODE_INVALID')
    validate(snapshot)
    test=next((t for t in snapshot['tests'] if t['id']==test_id),None)
    if not test:raise ValueError('READING_PAGE_MISSING')
    orth=next(o for o in snapshot['language']['orthographies'] if o['id']==snapshot['reading']['orthographyId'])
    forms={f['scalar']:dict(symbolId=s['id'],form=f['form']) for s in orth['symbols'] for f in s['forms']}
    rows=[]
    for i,p in enumerate(test['paragraphs']):
        text=p['text'];right=p['translation'] if mode=='translation' else text
        rows.append(dict(paragraph=i,left=text,right=right,sourceSha256=digest(text),rightSha256=digest(right),sameScalars=right==text,
                         maxima=sum(forms.get(ord(c),{}).get('form')=='maxima' for c in text),
                         minima=sum(forms.get(ord(c),{}).get('form')=='minima' for c in text)))
    return dict(engineVersion='1.0.0',mode=mode,policySha256=digest(snapshot['reading']),snapshotSha256=digest(snapshot),testId=test_id,testSha256=digest(test),paragraphs=rows,
                exactSlotsPreserved=all(r['sameScalars'] for r in rows) if mode!='translation' else None,
                fontSha256=ROMAN_SHA if mode=='transliteration' else None,
                status='Pass',scope='Font reading, not translation or Unicode respelling. Maxima/Minima are paired script forms; Unicode case is not used. Independent editable columns; rerun the frozen source after edits to refresh a reading.')


def pairs(state):
    if len(state['pages'])!=1 or len(state['pages'][0]['frames'])!=2:raise ValueError('READING_REQUIRES_ONE_PAGE_TWO_COLUMNS')
    return sorted(state['pages'][0]['frames'],key=lambda f:int(f['x']))


def text_blocks(frame):
    return [''.join(r.get('text',r.get('sourceText','')) for r in b['runs']) for b in frame['content']['document']['stories'][0]['blocks']]


def apply_font(state,face):
    """Only the right column font changes. Preserve sizes, leading and paint."""
    right=pairs(state)[1];doc=right['content']['document']
    for s in doc['styles']:s['fontId']=face.font_id
    if face.font_id not in {s['fontId'] for s in state['fontSources']}:state['fontSources'].append(dict(fontId=face.font_id,sha256=face.sha256,path=str(face.path)))
    # Font model entries are regenerated by the native frame serializer.
    if face.font_id not in {f['fontId'] for f in doc['fonts']}:doc['fonts'].append(dict(fontId=face.font_id,sha256=face.sha256,faceIndex=0))
    for block in doc['stories'][0]['blocks']:
        for run in block['runs']:
            text=run.pop('text',run.get('sourceText',''));run.update(type='legacy',sourceText=text,sourceFontSha256=face.sha256,mappingProfileRef=None,normalization='none',languageId='language.vayrshemon')


def presentation_matches(state,baseline,mode):
    from .forge_runner import presentation
    actual=presentation(state);expected=presentation(baseline)
    if mode!='translation':
        right_index=next(i for i,f in enumerate(state['pages'][0]['frames']) if f['frameId']==pairs(state)[1]['frameId'])
        for a,b in zip(actual['frameStyles'][right_index],expected['frameStyles'][right_index]):a['fontId']=b['fontId']
    return actual==expected


def sidebearing_review(layout,mode):
    """Retain the measured p overhang as review, not clipped or repaired text."""
    if mode!='transliteration' or layout.get('truncated'):return None
    frames=sorted(layout['frames'],key=lambda f:f['rect'][0]);left,right=frames
    if left['overflow'] or not right['overflow']:return None
    x,y,w,h=right['rect'];outside=[]
    for line in right['layout']['lines']:
        a,b,c,d=line['advanceBounds']
        if a<x-.01 or a+c>x+w+.01 or b<y-.01 or b+d>y+h+.01:return None
    for g in layout['glyphs']:
        if g['sourceFrameId']!=right['frameId']:continue
        a,b,c,d=g['inkBounds']
        if c<=0 or d<=0:continue
        if a<x-.01 or a+c>x+w+.01 or b<y-.01 or b+d>y+h+.01:
            if not (g['fontId']=='font:'+ROMAN_SHA+':0' and g['glyphId']==112 and 0<x-a<=.1 and a+c<=x+w+.01 and b>=y-.01 and b+d<=y+h+.01):return None
            outside.append(dict(sourceUtf16=g['sourceUtf16'],leftOverhangPoints=(x-a)*.75,glyphId=112,fontSha256=ROMAN_SHA))
    return dict(status='Needs review',glyphs=outside,details='Original transliteration 7 p has a negative sidebearing. All advances and vertical text fit; ink is retained without clipping, frame movement or font-size changes.') if outside else None


def copy(book,mode,directory):
    """Create a separate editable reading; never replace or modify its source."""
    from tools.m0.common import write_json,file_hash
    from .reliability_session import ReliabilitySession
    from . import pages
    from .forge_runner import align_paragraphs
    if mode not in ('transliteration','literal'):raise ValueError('READING_COPY_MODE_INVALID')
    out=Path(directory)
    if out.exists():raise ValueError('READING_DIRECTORY_EXISTS')
    source=book.capture();left,right=pairs(source)
    used={r.get('sourceFontSha256') for b in left['content']['document']['stories'][0]['blocks'] for r in b['runs']}
    if used!={SCRIPT_SHA}:raise ValueError('READING_REQUIRES_EXACT_THIMFORA_79')
    face=font(book,mode);state=deepcopy(source);state.update(documentId=identity('document'),revision=0,title=(source['title']+' · '+MODES[mode])[:200])
    for f in state['pages'][0]['frames']:f['content']['document']['documentId']=state['documentId']
    left,right=pairs(state);content=right['content'];doc=content['document'];prototype=deepcopy(doc['stories'][0]['blocks'][0]);blocks=[];characters=[];paragraphs=[];offset=0
    for text in text_blocks(left):
        b=deepcopy(prototype);b['blockId']=identity('block');r=deepcopy(b['runs'][0]);r['runId']=identity('run');r['sourceText' if r['type']=='legacy' else 'text']=text;b['runs']=[r];blocks.append(b)
        end=offset+utf16_length(text);characters.append(dict(start=offset,end=end,attributes=deepcopy(content['characters'][0]['attributes']) if content['characters'] else dict(tracking=0,wordSpacing=0,baseline=0)));offset=end+1
        paragraphs.append(dict(alignment='left',before=1.,after=24.,tabs=[]))
    doc['stories'][0]['blocks']=blocks;content.update(characters=characters,paragraphs=paragraphs);apply_font(state,face)
    out.mkdir(parents=True);payload=dict(format='vayrshemon.document',formatVersion=book.file_version,state=state,history=[],engine=book.fingerprint());write_json(out/'scaffold.vay.json',payload)
    temp=ReliabilitySession(book.root,source_fonts=False,recovery=False)
    try:
        temp.open(out/'scaffold.vay.json');align_paragraphs(temp,len(blocks));saved=temp.save(out/'reading.vay.json');rendered,render=pages.render(temp,path=out/'proof.png',mode='color',dpi=144)
        final=temp.capture();assert presentation_matches(final,source,mode);l,r=pairs(final);assert text_blocks(l)==text_blocks(r)
        layout=pages.inspect(temp,max_glyphs=20000);missing=sum(g['missingGlyph'] or bool(g.get('fallbackReason')) for g in layout['glyphs'])
        report=dict(mode=mode,document=str(out/'reading.vay.json'),documentSha256=file_hash(out/'reading.vay.json'),proof=str(out/'proof.png'),sourceDocumentId=source['documentId'],sourceRevision=source['revision'],sourceSha256=digest(source),sourceUnchanged=book.capture()==source,fontSha256=face.sha256,exactSlotsPreserved=True,presentationPreserved=True,overflow=sum(f['overflow'] for f in layout['frames']),missingGlyphs=missing,sidebearingReview=sidebearing_review(layout,mode),createdAt=stamp(),render=render)
        write_json(out/'reading.json',report);return report
    finally:temp.finish()
